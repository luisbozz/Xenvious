#!/usr/bin/env python3
"""Generates Xenvious/Generated/*.g.cs from the build data in Xenvious/OfflineData/<edition>/.

offsets.ini, scrpatches.json and prop_lists.json stay the files people and ysc-global-updater edit. Xenvious
does not read them at runtime any more: this turns them into C# with every value already a
number (paths resolved with their array size slots, see builddata.py), so the start does no
parsing and a key the code names but the files lack is a compile error instead of a silent 0.

    python3 tools/builddata/gen.py            write the generated files
    python3 tools/builddata/gen.py --check    exit 1 when they are not up to date (CI)

Run it after every change to those files; ysc-global-updater runs it after a deploy.
"""
from __future__ import annotations

import argparse
import json
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from builddata import number, parse_ini, section_kinds  # noqa: E402

ROOT = HERE.parents[1]
DATA = ROOT / "Xenvious" / "OfflineData"
OUT = ROOT / "Xenvious" / "Generated"
EDITIONS = (("legacy", "Legacy"), ("enhanced", "Enhanced"))

# The properties of GTA.ScrPatches / GTA.ScrPatchValue the generated lists set. A key in
# scrpatches.json that is neither here nor in IGNORED stops the run, so a new field cannot
# get lost on its way into the app.
PATCH_FIELDS = {
    "patch_name": "string", "script_name": "string", "pattern": "string", "offset": "int",
    "bytes_to_patch": "string", "dev": "bool", "trigger": "string", "page": "bool",
    "page_base": "int", "needs_page": "bool", "enabled": "bool",
}
VALUE_FIELDS = {"id": "int", "pattern": "string", "offset": "int", "bytes_to_read": "int"}
# Bookkeeping of ysc-global-updater, not read by the app.
IGNORED = {"category", "derived_for", "values"}

HEADER = """// <auto-generated>
// Generated by tools/builddata/gen.py from Xenvious/OfflineData. Do not edit: change the
// source files and run the script again.
// </auto-generated>
"""


def cs_string(s: str) -> str:
    out = []
    for ch in s:
        if ch in "\\\"":
            out.append("\\" + ch)
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\r":
            out.append("\\r")
        elif ch == "\t":
            out.append("\\t")
        elif ord(ch) < 0x20:
            out.append(f"\\u{ord(ch):04x}")
        else:
            out.append(ch)
    return '"' + "".join(out) + '"'


def load_inis():
    return {ed: parse_ini((DATA / ed / "offsets.ini").read_text(encoding="utf-8-sig"))
            for ed, _ in EDITIONS}


def sections_of(inis) -> list:
    seen = []
    for ini in inis.values():
        for sec, _ in ini:
            if sec not in seen:
                seen.append(sec)
    return seen


def gen_shape(inis) -> str:
    lines = [HEADER, "using System;", "", "namespace Xenvious", "{",
             "    /// <summary>The build data of one game edition (OfflineData/&lt;edition&gt;/offsets.ini).</summary>",
             "    public sealed partial class BuildData", "    {",
             "        /// <summary>The game build the values are for, e.g. \"1.73-3889\".</summary>",
             "        public string Build => BUILD.label;", ""]
    for sec in sections_of(inis):
        kinds = section_kinds(list(inis.values()), sec)
        cls = "Section_" + sec
        lines.append(f"        public readonly {cls} {sec} = new {cls}();")
        lines.append("")
        lines.append(f"        /// <summary>[{sec}]</summary>")
        lines.append(f"        public sealed class {cls}")
        lines.append("        {")
        for m, (kind, key) in kinds.items():
            init = " = \"\"" if kind == "string" else ""
            lines.append(f"            public {kind} {m}{init};")
        longs = [m for m, (k, _) in kinds.items() if k == "long"]
        kind = "long" if longs else "string"
        names = longs if longs else list(kinds)
        fallback = "0" if longs else '""'
        what = "number" if longs else "value"
        lines.append("")
        lines.append(f"            /// <summary>A {what} by name (the ini key without OFFSET_, any case), {fallback} when unknown.</summary>")
        lines.append(f"            public {kind} Get(string name)")
        lines.append("            {")
        lines.append('                switch ((name ?? "").ToLowerInvariant())')
        lines.append("                {")
        for m in names:
            lines.append(f"                    case {cs_string(m.lower())}: return {m};")
        lines.append(f"                    default: return {fallback};")
        lines.append("                }")
        lines.append("            }")
        lines.append("        }")
        lines.append("")
    lines += ["    }", "}", ""]
    return "\n".join(lines)


def gen_edition(inis, ed: str, Ed: str) -> str:
    ini = inis[ed]
    all_inis = list(inis.values())
    lines = [HEADER, "namespace Xenvious", "{", "    public sealed partial class BuildData", "    {",
             f"        private static BuildData Create{Ed}()", "        {", "            var d = new BuildData();"]
    for sec in sections_of(inis):
        kinds = section_kinds(all_inis, sec)
        lowmap = {key.lower(): m for m, (_, key) in kinds.items()}
        for (s, low), v in ini.items():
            if s != sec:
                continue
            m = lowmap.get(low)
            if m is None:
                # A second spelling of a key another edition names differently.
                from builddata import member_name
                m = member_name(ini.names[(s, low)])  # type: ignore[attr-defined]
            kind = kinds[m][0]
            if kind == "string":
                lines.append(f"            d.{sec}.{m} = {cs_string(v)};")
            else:
                n = number(v) if v.strip() else 0
                lines.append(f"            d.{sec}.{m} = {n};")
    lines += ["            return d;", "        }", "    }", "}", ""]
    return "\n".join(lines)


def cs_value(kind: str, v) -> str:
    if kind == "string":
        return cs_string(str(v))
    if kind == "bool":
        return "true" if v else "false"
    return str(int(v))


def gen_patches(ed: str, Ed: str) -> str:
    lines = [HEADER, "using System.Collections.Generic;", "", "namespace Xenvious", "{",
             "    public sealed partial class BuildData", "    {"]
    for fname, method in (("scrpatches.json", "ScrPatches"), ("scrpatchesdev.json", "ScrPatchesDev")):
        path = DATA / ed / fname
        patches = json.loads(path.read_text(encoding="utf-8-sig"))
        lines.append(f"        /// <summary>OfflineData/{ed}/{fname}, a new list on every call.</summary>")
        lines.append(f"        private static List<GTA.ScrPatches> {method}{Ed}()")
        lines.append("        {")
        lines.append("            return new List<GTA.ScrPatches>")
        lines.append("            {")
        for p in patches:
            unknown = set(p) - set(PATCH_FIELDS) - IGNORED
            if unknown:
                raise SystemExit(f"{path}: unknown field(s) {sorted(unknown)} in {p.get('patch_name')!r}; "
                                 "add them to GTA.ScrPatches and PATCH_FIELDS")
            parts = [f"{k} = {cs_value(PATCH_FIELDS[k], p[k])}" for k in PATCH_FIELDS if k in p]
            if "values" in p:
                vals = []
                for v in p["values"]:
                    bad = set(v) - set(VALUE_FIELDS)
                    if bad:
                        raise SystemExit(f"{path}: unknown value field(s) {sorted(bad)}")
                    vals.append("new GTA.ScrPatchValue { " + ", ".join(
                        f"{k} = {cs_value(VALUE_FIELDS[k], v[k])}" for k in VALUE_FIELDS if k in v) + " }")
                parts.append("values = new List<GTA.ScrPatchValue> { " + ", ".join(vals) + " }")
            lines.append("                new GTA.ScrPatches { " + ", ".join(parts) + " },")
        lines.append("            };")
        lines.append("        }")
        lines.append("")
    lines += ["    }", "}", ""]
    return "\n".join(lines)


def load_prop_lists() -> dict:
    return {ed: json.loads((DATA / ed / "prop_lists.json").read_text(encoding="utf-8-sig"))
            for ed, _ in EDITIONS}


def gen_prop_lists_shape(lists) -> str:
    names = []
    for data in lists.values():
        names += [k for k in data if k not in names]
    lines = [HEADER, "namespace Xenvious", "{",
             "    /// <summary>Model hash lists of one edition (OfflineData/&lt;edition&gt;/prop_lists.json),",
             "    /// spelled as the code compares them: hex for the first four, signed decimal for the rest.</summary>",
             "    public sealed class PropLists", "    {"]
    for k in names:
        lines.append(f"        public string[] {k} = new string[0];")
    lines += ["    }", "}", ""]
    return "\n".join(lines)


def gen_prop_lists(lists, ed: str, Ed: str) -> str:
    lines = [HEADER, "namespace Xenvious", "{", "    public sealed partial class BuildData", "    {",
             f"        /// <summary>OfflineData/{ed}/prop_lists.json, a new object on every call.</summary>",
             f"        private static PropLists PropLists{Ed}()", "        {", "            return new PropLists", "            {"]
    for k, values in lists[ed].items():
        if not all(isinstance(v, str) for v in values):
            raise SystemExit(f"OfflineData/{ed}/prop_lists.json: {k} must be a list of strings")
        lines.append(f"                {k} = new[]")
        lines.append("                {")
        for i in range(0, len(values), 8):
            lines.append("                    " + ", ".join(cs_string(v) for v in values[i:i + 8]) + ",")
        lines.append("                },")
    lines += ["            };", "        }", "    }", "}", ""]
    return "\n".join(lines)


def outputs() -> dict:
    inis = load_inis()
    lists = load_prop_lists()
    out = {"BuildData.g.cs": gen_shape(inis), "PropLists.g.cs": gen_prop_lists_shape(lists)}
    for ed, Ed in EDITIONS:
        out[f"BuildData.{Ed}.g.cs"] = gen_edition(inis, ed, Ed)
        out[f"ScrPatches.{Ed}.g.cs"] = gen_patches(ed, Ed)
        out[f"PropLists.{Ed}.g.cs"] = gen_prop_lists(lists, ed, Ed)
    return out


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true", help="only check, exit 1 when stale")
    a = ap.parse_args()
    stale = []
    for name, text in outputs().items():
        path = OUT / name
        old = path.read_text(encoding="utf-8-sig") if path.is_file() else None
        if old == text:
            continue
        stale.append(name)
        if not a.check:
            OUT.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
    if a.check:
        if stale:
            print("stale: " + ", ".join(stale) + " -- run python3 tools/builddata/gen.py")
            return 1
        print("generated files are up to date")
        return 0
    print(("written: " + ", ".join(stale)) if stale else "nothing to do")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
